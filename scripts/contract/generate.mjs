// pnpm contract:generate: regenerate types.generated.ts and fixtures.generated.ts from the vendored contract.
// Exports the pure generators too: check.mjs regenerates in memory and byte-compares (C2, C3).
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { LAYOUT, ROOT, readPin, sha256 } from './common.mjs';
import { FIXTURES, SATISFIES_TARGETS } from './registry.mjs';

/** The vendored examples, parsed, keyed by file name without extension (for example `MissionDetail.populated`). */
export function loadExamples(root = ROOT) {
  const dir = join(root, LAYOUT.examples);
  const out = {};
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.yaml') || name === '_index.yaml') continue;
    out[name.slice(0, -'.yaml'.length)] = parse(readFileSync(join(dir, name), 'utf8'));
  }
  return out;
}

/** Load a data-only or self-contained `.ts` file in plain Node (type stripping); the query busts the module cache by content. */
export async function importTs(file) {
  const hash = sha256(readFileSync(file)).slice(0, 16);
  return import(`${pathToFileURL(file).href}?h=${hash}`);
}

export const loadBulk = (root = ROOT) => importTs(join(root, LAYOUT.bulk));

const typesHeader = (pin) => `/**
 * Generated by \`pnpm contract:generate\` (openapi-typescript 7.13.0) from
 * contracts/spec-kitty/mission-status/openapi.yaml at spec-kitty ${pin.sha}
 * (mission-status contract ${pin.infoVersion}). Do not edit: the contract gate regenerates and byte-compares this file.
 */
`;

export async function generateTypesSource(root = ROOT) {
  const ast = await openapiTS(pathToFileURL(join(root, LAYOUT.openapi)));
  return typesHeader(readPin(root)) + astToString(ast);
}

const fixturesHeader = (pin) => `/**
 * Generated by \`pnpm contract:generate\` from the vendored examples of
 * contracts/spec-kitty/mission-status/examples at spec-kitty ${pin.sha}
 * and the named overlays of scripts/contract/overlays.mjs. Data only: type imports and \`satisfies\`, so plain Node
 * loads it by type stripping. Do not edit: the contract gate regenerates and byte-compares this file.
 */
`;

// A byte order mark inside a string is written as an escape: an invisible character in a generated file reviews as nothing.
const BYTE_ORDER_MARK = new RegExp(String.fromCharCode(0xfeff), 'g');
// Bidirectional controls are written as escapes: a raw one in a source file reorders how an editor shows the line.
const BIDI = new RegExp(`[${String.fromCharCode(0x200e, 0x200f)}${String.fromCharCode(0x202a)}-${String.fromCharCode(0x202e)}${String.fromCharCode(0x2066)}-${String.fromCharCode(0x2069)}]`, 'g');
const escapeBidi = (text) => text.replace(BIDI, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
const literal = (doc) =>
  escapeBidi(
    JSON.stringify(doc, null, 2)
      .replace(/^(\s*)"([A-Za-z_][A-Za-z0-9_]*)":/gm, '$1$2:')
      .replace(BYTE_ORDER_MARK, `${String.fromCharCode(92)}uFEFF`),
  );

/** `buildFixtures` and `bulk` default to the repository's own; tests inject changed ones. */
export async function generateFixturesSource(root = ROOT, deps = {}) {
  const overlays = deps.buildFixtures ? { buildFixtures: deps.buildFixtures } : await import('./overlays.mjs');
  const bulk = deps.bulk ?? (await loadBulk(root));
  const registry = deps.registry ?? FIXTURES;
  const docs = overlays.buildFixtures({ examples: loadExamples(root), bulk });
  const targets = deps.registry ? [...new Set(Object.values(registry).map((x) => x.satisfies))].sort() : SATISFIES_TARGETS;
  let out = `${fixturesHeader(readPin(root))}import type { ${targets.join(', ')} } from './types.js';\n`;
  for (const [name, def] of Object.entries(registry)) {
    out += `\n// fixture: ${name}\nexport const ${name} = ${literal(docs[name])} satisfies ${def.satisfies};\n`;
  }
  return out;
}

export async function generateAll(root = ROOT) {
  writeFileSync(join(root, LAYOUT.types), await generateTypesSource(root));
  writeFileSync(join(root, LAYOUT.fixtures), await generateFixturesSource(root));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateAll();
  process.stdout.write('contract:generate: wrote types.generated.ts and fixtures.generated.ts\n');
}
